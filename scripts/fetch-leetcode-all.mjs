// Regenerates src/data/leetcodeAll.ts from LeetCode's public GraphQL API.
//
//   node scripts/fetch-leetcode-all.mjs
//
// Only the "Algorithms" problem set is kept (no SQL / Pandas / JavaScript /
// Shell / Concurrency drills). Each problem gets one pattern-style category
// derived from its topic tags, so stats like "weakest category" stay readable.

import { writeFileSync } from 'node:fs'

const PAGE = 100
const OUT = new URL('../src/data/leetcodeAll.ts', import.meta.url)

const QUERY = `query q($skip: Int, $limit: Int) {
  questionList(categorySlug: "algorithms", limit: $limit, skip: $skip, filters: {}) {
    totalNum
    data {
      questionFrontendId
      title
      titleSlug
      difficulty
      isPaidOnly
      topicTags { name }
    }
  }
}`

async function page(skip) {
  const res = await fetch('https://leetcode.com/graphql', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Referer: 'https://leetcode.com/problemset/',
      'User-Agent': 'Mozilla/5.0',
    },
    body: JSON.stringify({ query: QUERY, variables: { skip, limit: PAGE } }),
  })
  if (!res.ok) throw new Error(`LeetCode responded ${res.status}`)
  return (await res.json()).data.questionList
}

/** First matching tag wins, so more specific patterns come first. */
const CATEGORY_RULES = [
  ['Tries', ['Trie']],
  ['Advanced Graphs', ['Shortest Path', 'Minimum Spanning Tree', 'Eulerian Circuit', 'Strongly Connected Component', 'Biconnected Component']],
  ['Graphs', ['Graph Theory', 'Graph', 'Topological Sort', 'Union-Find', 'Union Find']],
  ['Dynamic Programming', ['Dynamic Programming', 'Memoization']],
  ['Backtracking', ['Backtracking']],
  ['Heap / Priority Queue', ['Heap (Priority Queue)']],
  ['Trees', ['Tree', 'Binary Tree', 'Binary Search Tree', 'Segment Tree', 'Binary Indexed Tree']],
  ['Linked List', ['Linked List', 'Doubly-Linked List']],
  ['Sliding Window', ['Sliding Window']],
  ['Binary Search', ['Binary Search']],
  ['Stack', ['Stack', 'Monotonic Stack', 'Queue', 'Monotonic Queue']],
  ['Graphs', ['Breadth-First Search', 'Depth-First Search']],
  ['Two Pointers', ['Two Pointers']],
  ['Greedy', ['Greedy']],
  ['Bit Manipulation', ['Bit Manipulation', 'Bitmask']],
  ['Math & Geometry', ['Math', 'Geometry', 'Matrix', 'Number Theory', 'Combinatorics']],
  ['Design', ['Design', 'Data Stream', 'Iterator']],
]
const FALLBACK = 'Arrays & Hashing'

function categoryOf(tags) {
  const names = new Set(tags.map((t) => t.name))
  for (const [category, match] of CATEGORY_RULES) {
    if (match.some((m) => names.has(m))) return category
  }
  return FALLBACK
}

const first = await page(0)
const all = [...first.data]
for (let skip = PAGE; skip < first.totalNum; skip += PAGE) {
  all.push(...(await page(skip)).data)
}
all.sort((a, b) => Number(a.questionFrontendId) - Number(b.questionFrontendId))

const categories = [...new Set([...CATEGORY_RULES.map(([c]) => c), FALLBACK])]
const rows = all.map((q) =>
  JSON.stringify([
    Number(q.questionFrontendId),
    q.titleSlug,
    q.title,
    q.difficulty[0],
    categories.indexOf(categoryOf(q.topicTags)),
    q.isPaidOnly ? 1 : 0,
  ]),
)

const ts = `import { lc, type Difficulty, type Problem } from './types'

/**
 * LeetCode All — every problem in LeetCode's "Algorithms" set, ordered by
 * problem number. Ids are LeetCode slugs, so progress syncs with every other
 * list. Names carry the problem number so you can search by it.
 *
 * GENERATED by scripts/fetch-leetcode-all.mjs — don't edit by hand.
 * Rows: [number, slug, title, difficulty initial, category index, premium].
 */

const CATEGORIES = ${JSON.stringify(categories)}

const DIFFICULTY: Record<string, Difficulty> = { E: 'Easy', M: 'Medium', H: 'Hard' }

const ROWS: [number, string, string, string, number, number][] = [
${rows.map((r) => `  ${r},`).join('\n')}
]

export const LEETCODE_ALL: Problem[] = ROWS.map(([num, id, title, diff, cat, premium]) => ({
  id,
  name: \`\${num}. \${title}\`,
  category: CATEGORIES[cat],
  difficulty: DIFFICULTY[diff],
  link: lc(id),
  ...(premium ? { premium: true } : {}),
}))
`

writeFileSync(OUT, ts)
console.log(`Wrote ${all.length} problems to src/data/leetcodeAll.ts`)
